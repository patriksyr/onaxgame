CREATE TABLE users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 username VARCHAR(24) CHARACTER SET ascii COLLATE ascii_general_ci NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 coins INT UNSIGNED NOT NULL DEFAULT 100,
 is_admin BOOLEAN NOT NULL DEFAULT FALSE,
 last_daily DATE NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;
CREATE TABLE cards (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 description VARCHAR(500) NOT NULL,
 rarity ENUM('common','rare','epic','legendary','mythic') NOT NULL,
 image VARCHAR(255) NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
CREATE TABLE purchases (
 id CHAR(32) CHARACTER SET ascii PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 request_key VARCHAR(64) CHARACTER SET ascii NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY unique_request (user_id, request_key),
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB;
CREATE TABLE inventory (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 card_id BIGINT UNSIGNED NOT NULL,
 purchase_id CHAR(32) CHARACTER SET ascii NOT NULL,
 sold_at DATETIME NULL,
 acquired_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (user_id) REFERENCES users(id),
 FOREIGN KEY (card_id) REFERENCES cards(id),
 FOREIGN KEY (purchase_id) REFERENCES purchases(id),
 KEY owned_cards (user_id, sold_at)
) ENGINE=InnoDB;
CREATE TABLE auth_attempts (
 ip_hash CHAR(64) CHARACTER SET ascii PRIMARY KEY,
 attempts INT UNSIGNED NOT NULL DEFAULT 0,
 window_start BIGINT NOT NULL
) ENGINE=InnoDB;
